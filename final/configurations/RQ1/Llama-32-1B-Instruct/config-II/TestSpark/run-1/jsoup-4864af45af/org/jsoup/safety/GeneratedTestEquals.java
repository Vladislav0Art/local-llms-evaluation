package org.jsoup.safety;

import org.junit.Test;

public class GeneratedTestEquals {

    @Test
    public void testEquals() {
        TypedValue value1 = new AttributeKey("value");
        TypedValue value2 = new AttributeKey("value");
        TypedValue value3 = null;
        assertFalse(value1.equals(value2));
        assertFalse(value1.equals(value3));
    }

}