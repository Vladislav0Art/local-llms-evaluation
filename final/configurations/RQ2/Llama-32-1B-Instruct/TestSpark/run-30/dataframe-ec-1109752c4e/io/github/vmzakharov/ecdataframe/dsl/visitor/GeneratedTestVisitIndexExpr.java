package io.github.vmzakharov.ecdataframe.dsl.visitor;

import org.eclipse.collections.api.list.ListIterable;
import org.eclipse.collections.impl.utility.StringIterate;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

public class GeneratedTestVisitIndexExpr {

    private PrettyPrintVisitor visitor;
    private Printer newPrinter;

    @BeforeEach
    public void setup() {
        visitor = new PrettyPrintVisitor();
        newPrinter = mock(Printer.class);
    }

    @Test
    public void testVisitIndexExpr() {
        Expression expr = StringIterate.generate("a[0]", ListIterable.of(2)).toExpression();
        when(expr.toString()).thenReturn("");

        visitor.visitIndexExpr(expr);

        verify(newPrinter).print("a[0]", "a[0]");
    }

}